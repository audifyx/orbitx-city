// HERO POWERS — 60 renamed TV-inspired heroes (launch-safe versions).
// Pure logic: no three.js, no DOM, no imports — unit-testable in node via
// esbuild (same pattern as the doors-floor probe). The runtime (runtime.ts)
// owns the live state (cooldowns, projectiles, NPC overrides) and calls
// these helpers; nothing here touches the scene.
//
// Power model: every hero look maps to exactly one PowerDef. The library
// has 10 effect kinds; each hero gets one def with per-hero tuning
// (cooldown / range / duration / speed). Press powers fire once per press
// (KeyY / HUD Power button); hold powers stay active while held
// (Speed Force family). Trick arrows cycle one type per shot.
//
// Kinds:
//   speed-hold  — hold to run faster (Speed Force, Reverse Speed)
//   speed-press — press for a timed speed buff (bursts, rushes)
//   projectile  — a real flying mesh (arrows, bolts, bullets, stars,
//                 freeze ray, fire blast); trick arrows cycle 3 types
//   melee       — arc/range hit: knockback + NPCs flee
//   rally       — nearby NPCs follow the moving player
//   gather      — nearby NPCs stop and gather at the activation point
//   stealth     — undetectable to NPCs + translucency
//   reveal      — gold beacons above nearby NPCs (tracking)
//   aoe         — area effect on NPCs: wait (freeze/trap), flee, knockback
//   breach      — teleport forward a fixed distance
// Secondary effects ride on a def: revealRadius (tracking ping after a
// shot / during a sprint), rallyRadius (followers during a speed buff),
// aoeMode/aoeRadius/aoeDurationMs (area effect attached to a press).

export type PowerKind =
  | "speed-hold"
  | "speed-press"
  | "projectile"
  | "melee"
  | "rally"
  | "gather"
  | "stealth"
  | "reveal"
  | "aoe"
  | "breach";

export type ProjectileKind = "arrow" | "bolt" | "bullet" | "star" | "freeze" | "fire";

export type AoeMode = "wait" | "flee" | "knockback";

export type TrickArrow = "standard" | "explosive" | "smoke";

export const TRICK_ARROWS: TrickArrow[] = ["standard", "explosive", "smoke"];

export const TRICK_ARROW_LABEL: Record<TrickArrow, string> = {
  standard: "Standard",
  explosive: "Explosive",
  smoke: "Smoke",
};

export interface PowerDef {
  id: string;
  /** Effect kind — the runtime dispatches on this. */
  kind: PowerKind;
  /** Hero look id (characters.json). */
  heroId: string;
  heroName: string;
  name: string;
  blurb: string;
  key: string;
  /** Cooldown after the power ends (ms). */
  cooldownMs: number;
  /** How long the effect lasts once active (ms, 0 = instant). */
  durationMs: number;
  /** Melee / projectile / aura radius in world units. */
  range: number;
  /** Melee arc in degrees (360 = full sweep). */
  arcDeg: number;
  /** True = active while held (Speed Force family). */
  hold: boolean;
  /** Speed multiplier while the power is active. */
  speedMult?: number;
  /** True = fires trick arrows, one type per shot. */
  trick?: boolean;
  /** Projectile flavour (projectile kind only). */
  proj?: ProjectileKind;
  /** Projectile flight speed in world units / second. */
  projSpeed?: number;
  /** True = scope/zoom feel while firing (long-range shots). */
  scope?: boolean;
  /** Melee knockback strength in world units. */
  knockback?: number;
  /** Area effect attached to this power (aoe kind, or secondary). */
  aoeMode?: AoeMode;
  aoeRadius?: number;
  aoeDurationMs?: number;
  /** Secondary tracking ping: beacons above NPCs within this radius. */
  revealRadius?: number;
  revealDurationMs?: number;
  /** Secondary rally: NPCs within this radius follow while active. */
  rallyRadius?: number;
  rallyDurationMs?: number;
  /** Breach distance in world units (breach kind only). */
  teleport?: number;
}

