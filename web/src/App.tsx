// Build the panel rows from one my-properties snapshot. The server sends
// the raw facts (owned lot ids, claims, homes); the client resolves
// display names, towers and anchors from its own catalogs.
function buildMyPropertyRows(data: { server: number; lots: string[]; offices: MyPropertyClaim[]; homes: { homeId: string; server: number; price: number }[] }): MyPropertyRow[] {
  const rows: MyPropertyRow[] = [];
  for (const lotId of data.lots) {
    const meta = LOT_META[lotId];
    if (!meta) continue;
    rows.push({
      key: lotId,
      kind: meta.kind === "hq" ? "hq" : "lot",
      name: meta.name,
      where: meta.where,
      detail: meta.detail,
      anchor: meta.anchor,
      manage: meta.manage,
    });
  }
  for (const claim of data.offices) {
    const meta = resolveOfficeSuite(claim.suite);
    if (!meta) continue;
    rows.push({
      key: claim.suite,
      kind: "office",
      name: claim.project || meta.name,
      where: `${meta.name} · ${meta.tower} · Floor ${meta.floor}`,
      detail: `Office lease until ${claim.until} · ${claim.price} City Sol paid`,
      anchor: meta.anchor,
      manage: meta.manage,
      district: meta.district,
      suite: claim.suite,
    });
  }
  for (const home of data.homes) {
    const def = homeById(home.homeId);
    const state = def ? stateById(def.state) : null;
    const district = def ? DISTRICTS.find((d) => d.id === def.district) : null;
    rows.push({
      key: home.homeId,
      kind: "home",
      name: def?.name ?? home.homeId,
      where: def ? `${state?.name ?? def.state} · ${district?.name ?? def.district}` : home.homeId,
      detail: `${home.price} City Sol · Server ${home.server}`,
      anchor: home.homeId,
      manage: null,
    });
  }
  return rows;
}

// Same bearer pattern as the game world's own API calls: account token
// first, guest player token (localStorage "orbitx-token") second.
async function callCity(op: string, extra: Record<string, unknown> = {}) {
  const headers: Record<string, string> = { "content-type": "application/json" };
  const token = accountToken() || localStorage.getItem("orbitx-token") || "";
  if (token) headers.authorization = `Bearer ${token}`;
  const response = await fetch("/api/city", {
    method: "POST",
    headers,
    body: JSON.stringify({ op, ...extra }),
  });
  return (await response.json()) as Record<string, unknown>;
}

