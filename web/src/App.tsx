// One row in the HUD's "My Properties" panel — everything the player owns
// on the current universe, with the anchor the "Go to" button jumps to
// and the panel "Manage" opens (null where there is no panel for it —
// state tower offices have no directory panel, so they get "Go to" only).
interface MyPropertyRow {
  key: string;
  kind: "hq" | "lot" | "office" | "home";
  name: string;
  where: string;
  detail: string;
  anchor: string;
  manage: "hq" | "home" | "offices" | "district-offices" | null;
  district?: DistrictId;
  suite?: string;
}

// Resolve an office claim's suite id to its tower, floor, display name
// and the anchor "Go to" lands on. HQ suites live in the OrbitX Tower,
// district suites in their district tower, state suites in their state
// tower. Returns null for an id no catalog knows.
//
// ORDER MATTERS: OFFICE_SUITES is the union of the HQ tower's 25 suites
// AND the 36 state suites (ny/la/fl, floors 2-4), so a blind OFFICE_SUITES
// lookup first would mis-route a state suite to the HQ tower (wrong
// "OrbitX Tower" label, wrong orbitx-hq door, a Manage button that opens
// the HQ panel). District and state suites are generated by their own
// catalogs, so they are checked first; anything left in OFFICE_SUITES
// after that is genuinely an HQ suite.
function resolveOfficeSuite(suiteId: string): { name: string; floor: number; tower: string; anchor: string; manage: "offices" | "district-offices" | null; district?: DistrictId } | null {
  for (const district of DISTRICTS) {
    const found = districtOfficeSuites(district.id).find((suite) => suite.id === suiteId);
    if (found) return { name: found.name, floor: found.floor, tower: district.towerName, anchor: `tower-${district.id}`, manage: "district-offices", district: district.id };
  }
  for (const stateId of ["ny", "la", "fl"] as const) {
    const found = stateOfficeSuites(stateId).find((suite) => suite.id === suiteId);
    if (found) {
      const state = stateById(stateId);
      return { name: found.name, floor: found.floor, tower: `${state.name} Tower`, anchor: `${stateId}-offices`, manage: null };
    }
  }
  const hq = OFFICE_SUITES.find((suite) => suite.id === suiteId);
  if (hq) return { name: hq.name, floor: hq.floor, tower: "OrbitX Tower", anchor: "orbitx-hq", manage: "offices" };
  return null;
}

